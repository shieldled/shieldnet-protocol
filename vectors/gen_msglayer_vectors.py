#!/usr/bin/env python3
"""
ShieldNet message-layer golden-vector generator.

Computes the reference frames for spec/message-layer.md §4 (header, AAD, nonce),
§6.2 (padding, size classes) and Appendix A from an implementation independent of
any other: XChaCha20-Poly1305 is built here from HChaCha20 over the
`cryptography` library's IETF ChaCha20-Poly1305. The LZ4 case is a DECODE vector: the block is a hand-written
literal-only block, because LZ4 compressors are not canonical and two conforming
senders may emit different blocks for one plaintext.

Run:  python3 vectors/gen_msglayer_vectors.py > vectors/shieldnet-msglayer-vectors.json
"""
import json, struct, sys
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305

def rotl(v, n): return ((v << n) & 0xFFFFFFFF) | (v >> (32 - n))
def qr(s, a, b, c, d):
    s[a] = (s[a] + s[b]) & 0xFFFFFFFF; s[d] = rotl(s[d] ^ s[a], 16)
    s[c] = (s[c] + s[d]) & 0xFFFFFFFF; s[b] = rotl(s[b] ^ s[c], 12)
    s[a] = (s[a] + s[b]) & 0xFFFFFFFF; s[d] = rotl(s[d] ^ s[a], 8)
    s[c] = (s[c] + s[d]) & 0xFFFFFFFF; s[b] = rotl(s[b] ^ s[c], 7)
def hchacha20(key, n16):
    s = list(struct.unpack("<4I", b"expand 32-byte k")) + \
        list(struct.unpack("<8I", key)) + list(struct.unpack("<4I", n16))
    for _ in range(10):
        qr(s, 0, 4, 8, 12); qr(s, 1, 5, 9, 13); qr(s, 2, 6, 10, 14); qr(s, 3, 7, 11, 15)
        qr(s, 0, 5, 10, 15); qr(s, 1, 6, 11, 12); qr(s, 2, 7, 8, 13); qr(s, 3, 4, 9, 14)
    return struct.pack("<8I", *(s[0:4] + s[12:16]))
def xseal(key, nonce24, aad, pt):
    sub = hchacha20(key, nonce24[:16])
    return ChaCha20Poly1305(sub).encrypt(b"\x00" * 4 + nonce24[16:], pt, aad)

FLAG_COMPRESSED = 0x80000000
def nonce(num): return b"\x00" * 8 + struct.pack(">Q", num) + b"\x00" * 8
def pad_class(n):
    c = 64
    while c < n: c <<= 1
    return c
def frame(key, msg_type, num, plaintext, body):
    hdr = struct.pack(">IIIQ", len(body) + 16, len(plaintext), msg_type, num)
    return hdr, hdr + xseal(key, nonce(num), hdr, body)

key = bytes(0xA0 + i for i in range(32))
payload = b"shieldnet message layer golden vector payload"
num = 0x0102030405060708
out = {"_comment": "Generated by vectors/gen_msglayer_vectors.py from the formulas in spec/message-layer.md; independent of any implementation. Do not hand-edit.",
       "key": key.hex(), "cases": []}
def case(name, msg_type, n, pt, body):
    hdr, fr = frame(key, msg_type, n, pt, body)
    out["cases"].append({"name": name, "message_type": "%08x" % msg_type,
        "message_num": "%016x" % n, "nonce": nonce(n).hex(), "plaintext": pt.hex(),
        "sealed_body": body.hex(), "header_aad": hdr.hex(), "frame": fr.hex()})

case("plain", 0x00112233, num, payload, payload)
case("padded", 0x00000007, 1, b"", b"\x00" * 64)                       # PING, empty, class 64
case("padded-45", 0x00000060, 2, payload, payload + b"\x00" * (pad_class(len(payload)) - len(payload)))
lit = b"A" * 40                                                          # literal-only LZ4 block
lz4_block = bytes([0xF0, 40 - 15]) + lit
case("compressed-decode", 0x00000000 | FLAG_COMPRESSED, 3, lit, lz4_block)
json.dump(out, sys.stdout, indent=1); print()
